/** English message tree; its dotted paths are the "admin." keys of the attendance pack. */
export const ADMIN_EN = en;
export type AdminText = Bound<typeof en> & { questionIssue(issue: QuestionIssue): string };

const bound = new WeakMap<object, AdminText>();
let english: AdminText | undefined;

function bind(catalog: Catalog | null, locale: string): AdminText {
  const text = bindMessages(en, catalog, locale) as AdminText;
  text.questionIssue = (issue: QuestionIssue) => {
    const p = { hasLine: !!issue.line, line: issue.line ?? "", limit: issue.limit ?? "", value: issue.value ?? "" };
    const templates = text.questionIssues as Record<string, (params: object) => string>;
    return (templates[issue.code] ?? templates.INVALID!)(p);
  };
  return text;
}

/** Admin texts for a pack catalog (null = English). Bound once per catalog per isolate. */
export function adminText(catalog?: Catalog | null, locale = "en"): AdminText {
  if (!catalog) return (english ??= bind(null, "en"));
  let text = bound.get(catalog);
  if (!text) bound.set(catalog, (text = bind(subtree(catalog, "admin."), locale)));
  return text;
}

/** Catalog entries under a prefix, without it ("admin.save" → "save"). */
export function subtree(catalog: Catalog, prefix: string): Catalog {
  const out: Catalog = {};
  for (const key in catalog) if (key.startsWith(prefix)) out[key.slice(prefix.length)] = catalog[key]!;
  return out;
}
